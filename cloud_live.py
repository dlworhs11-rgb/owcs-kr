"""Build the public site folder for GitHub Pages: the whole data build runs here, so the site needs no PC.

Runs in GitHub Actions (.github/workflows/pages.yml) every ~10 min, on every push and by hand:
  1. collector (github.com/dlworhs11-rgb/OWCSKR, checked out in ./OWCSKR, Liquipedia cache kept by actions/cache):
     re-read the active Liquipedia pages when the copy is older than 30 min (10 min around today's matches),
     pick up the next stage once Liquipedia links it, then node collector/build.mjs
  2. owcs_build.build(): schedule, results, standings, brackets, players -> owcs-data.js
     (+ data/live_scores and data/live_maps pushed from the PC on match days); if it fails, the deployed copy stays
  3. refresh `live` (which players stream on CHZZK / SOOP) and match-day SOOP VOD links
  4. rebuild the calendar-subscription files (matches not played yet)
  4b. stamp each page's own scripts with a content hash (owcs-i18n.js?v=1a2b3c4d), so a browser never mixes a new page
      with a script it cached before the deploy (GitHub Pages caches for 10 min: 10-20 "OWCSi18n.hm is not a function")
  5. set `liveChecked` = now; bump `generated` only when the content really changed,
     so open pages reload only when there is something new; owcs-ver.json and owcs-data.js?v= carry a hash of the
     content without those fields (content_hash), so a build that changed nothing is not downloaded again (10-24)

Usage:
  python cloud_live.py --out _site [--prev https://<user>.github.io/<repo>/owcs-data.js] [--force-lp]
"""
import gzip, json, os, re, shutil, subprocess, sys, time, datetime, traceback, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.makedirs(os.path.join(HERE, 'data'), exist_ok=True)   # soop_vods() caches here
import owcs_cloud as b  # noqa: E402
import owcs_build  # noqa: E402
import site_urls  # noqa: E402

SITE_FILES = site_urls.SITE_FILES   # the one list of deployed root files lives in site_urls.py
VOLATILE = ('generated', 'liveChecked', 'igChecked')
COLLECTOR = os.path.dirname(owcs_build.SRC)
LP_API = 'https://liquipedia.net/overwatch/api.php'
LP_UA = 'OWCSKR-fansite/0.1 (+https://github.com/dlworhs11-rgb/OWCSKR)'   # same as the collector


def read_data(text):
    return json.loads(text[text.index('=') + 1:].strip().rstrip(';'))


def write_data(path, data):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// generated by owcs_build.py + cloud_live.py - do not edit\nwindow.OWCS = '
                + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')   # no spaces: -10% (10-24)


def flag(msg):
    """a yellow warning on the Actions run page and in its summary: a failed step here still deploys (the last
    deploy's data stays), so the run is green and a broken build went unseen"""
    if not os.environ.get('GITHUB_ACTIONS'):
        return
    print('::warning::' + msg.replace('%', '%25').replace('\r', '%0D').replace('\n', '%0A'))
    if os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a', encoding='utf-8') as f:
            f.write('- ' + msg.replace('\n', ' ') + '\n')


def fetch_prev(url):
    try:
        req = urllib.request.Request(url + '?v=' + str(int(datetime.datetime.now().timestamp())), headers={'User-Agent': 'Mozilla/5.0'})
        return read_data(urllib.request.urlopen(req, timeout=15).read().decode('utf-8'))
    except Exception as e:
        print('previous deploy not readable:', e)
        return None


def cache_file(title):
    return os.path.join(owcs_build.SRC, 'lp-cache', re.sub(r'[^a-z0-9]+', '_', title, flags=re.I) + '.wiki')


def active_titles():
    """the pages `node collector/run-lp.mjs --active-only` re-reads (same filter as the collector)"""
    with open(os.path.join(owcs_build.SRC, 'competitions.json'), encoding='utf-8') as f:
        comps = json.load(f)
    with open(os.path.join(owcs_build.SRC, 'active.json'), encoding='utf-8') as f:
        active = json.load(f)
    titles = comps['core'] + [t for t in comps.get('world_cup', []) if re.search(r'20(23|26)$', t)]
    return [t for t in titles if any(a in t for a in active)]


def match_window(prev, now):
    """around today's matches (30 min before the first until 4 h after the last start): results change fast"""
    starts = [datetime.datetime.fromisoformat(m['date']) for m in (prev or {}).get('matches', []) if m.get('day') == now.date().isoformat()]
    return bool(starts) and min(starts) - datetime.timedelta(minutes=30) <= now <= max(starts) + datetime.timedelta(hours=4)


def node(*args):
    r = subprocess.run(['node', *args], cwd=COLLECTOR, capture_output=True, text=True, encoding='utf-8', errors='replace', timeout=600)
    print(f"node {' '.join(args)}: " + ' | '.join((r.stdout or '').strip().splitlines()[-3:]))
    if r.returncode:
        raise RuntimeError(f"node {' '.join(args)} failed: {(r.stderr or r.stdout).strip()[-300:]}")


def mark_fetched():
    if os.environ.get('GITHUB_OUTPUT'):   # the workflow saves the Liquipedia cache only when this run read something new
        with open(os.environ['GITHUB_OUTPUT'], 'a') as f:
            print('fetched=true', file=f)


def ensure_wiki(titles):
    """Liquipedia pages the build reads but the collector does not re-fetch (an older stage's playoff page).
    A page read here is saved with the cache too (10-20: it was not, so every run asked again until Liquipedia
    answered 429 and the site lost its brackets); on a 429 the rest wait for the next run instead of asking again.
    A page Liquipedia does not have yet (this year's events before they are created) is noted in lp-cache/_missing.json
    and asked again after 6 h, not on every run (10-24: it was asked every run, and printed nothing)"""
    seen_f = os.path.join(owcs_build.SRC, 'lp-cache', '_missing.json')
    try:
        with open(seen_f, encoding='utf-8') as fh:
            missing = json.load(fh)
    except (OSError, ValueError):
        missing = {}
    for t in titles:
        f = cache_file(t)
        if os.path.exists(f) or time.time() - missing.get(t, 0) < 6 * 3600:
            continue
        url = LP_API + '?' + urllib.parse.urlencode(dict(format='json', action='query', prop='revisions', rvprop='content', rvslots='main', titles=t))
        try:
            req = urllib.request.Request(url, headers={'User-Agent': LP_UA, 'Accept-Encoding': 'gzip'})
            r = json.loads(gzip.decompress(urllib.request.urlopen(req, timeout=30).read()))
            text = (list(r['query']['pages'].values())[0].get('revisions') or [{}])[0].get('slots', {}).get('main', {}).get('*')
            if text is not None:
                os.makedirs(os.path.dirname(f), exist_ok=True)
                with open(f, 'w', encoding='utf-8') as fh:
                    fh.write(text)
                print('fetched', t)
                mark_fetched()
            else:
                missing[t] = time.time()
                os.makedirs(os.path.dirname(seen_f), exist_ok=True)
                with open(seen_f, 'w', encoding='utf-8') as fh:
                    json.dump(missing, fh, ensure_ascii=False)
                print('missing on Liquipedia, asked again in 6 h:', t)
                mark_fetched()   # the workflow saves lp-cache (with this note) only on a run that marks it
        except Exception as e:
            print('not fetched:', t, e)
            if getattr(e, 'code', None) == 429:
                return
        time.sleep(2.2)   # Liquipedia API terms: at most 1 request / 2 s


def read_replays():
    """replay codes: the community sheet (one Google CSV, ~1 s), read on every build. Read only with Liquipedia it was
    missing from the runs in between, which then used the collector's committed copy (10-11) and dropped newer codes (10-19)"""
    try:
        node('collector/replays.mjs', '--refresh')
    except Exception as e:
        print('replay sheet not read:', e)


def collect(prev, now, force=False):
    """refresh the collector data (data/lp, data/site) from Liquipedia when it is old enough"""
    titles = active_titles()
    stamp = os.path.join(owcs_build.SRC, 'lp-cache', '_fetched.txt')   # last re-read (file times may not survive the cache)
    age = now.timestamp() - float(open(stamp).read()) if os.path.exists(stamp) else None
    limit = 600 if match_window(prev, now) else 1800
    if force or age is None or age > limit - 60:
        for t in titles:   # the collector keeps its copy for 6 h: date it back so the pages are read again now
            if os.path.exists(cache_file(t)):   # (kept, so a failed read still leaves the old copy)
                os.utime(cache_file(t), (0, 0))
        node('collector/run-lp.mjs', '--active-only')
        os.makedirs(os.path.dirname(stamp), exist_ok=True)
        with open(stamp, 'w') as f:
            f.write(str(now.timestamp()))
        print(f'Liquipedia re-read ({len(titles)} pages, limit {limit // 60} min)')
        mark_fetched()
    else:
        print(f'Liquipedia copy is {int(age // 60)} min old (limit {limit // 60} min): not re-read')
    read_replays()
    node('collector/build.mjs')
    try:   # next stage linked on Liquipedia: fetch it too (only in this checkout, the collector repo is not changed)
        nxt = owcs_build.next_stage_pages()
        if nxt:
            owcs_build.add_next_stage(nxt)
            print('next stage added for this run:', *nxt)
            node('collector/run-lp.mjs', '--active-only')
            node('collector/build.mjs')
    except Exception as e:
        print('next stage check skipped:', e)
    stages = owcs_build.find_stages()
    cur = owcs_build.current_stage(stages, now.date())
    i = stages.index(cur)
    # every stage of this year (the results page picks any of them; 10-22: stage 1 had no bracket, so its playoffs were one
    # 플레이오프 block) plus the one before, for last season's bracket in January
    ensure_wiki([s['po'].replace('OWCS ', owcs_build.LP_NAME + '/', 1) for j, s in enumerate(stages[:i + 1]) if s['year'] == cur['year'] or j == i - 1])
    # the season's international events: dates and city (infobox), group / round names when the collector has none
    ensure_wiki([f"{owcs_build.LP_NAME}/{cur['year']}/{name}{sub}" for name, _, _ in owcs_build.INTL_EVENTS for sub in ('', '/Group Stage')])


def content_hash(data):
    """owcs-data.js's version: a hash of the data without the fields every build rewrites (VOLATILE). The file's own
    hash changed on every run because of liveChecked, so open pages downloaded an unchanged ~48 KB (gzip) file ~13 times
    an hour (10-24: 24 'unchanged' builds in a row, 24 new hashes). liveChecked goes to owcs-ver.json beside it."""
    import hashlib
    body = json.dumps({k: v for k, v in data.items() if k not in VOLATILE}, sort_keys=True, ensure_ascii=False)
    return hashlib.sha1(body.encode('utf-8')).hexdigest()[:8]


def carry_over(prev_matches, matches):
    """the last deploy's matches this build lacks (a Liquipedia page missing this run, 429): put back, not dropped.
    A regular-season match's id carries its day (owcs_build: f"{day}-{idx}"), so a rescheduled one comes back under a new
    id; the old one is not put back when this build has a regular-season match of the same two teams (10-24: it stayed
    on the schedule, the results and the calendar until the stage ended). One meeting per pair in the regular season
    (2026: 9 teams, single round robin): look again if a season plays each pair twice."""
    ids = {m['id'] for m in matches}
    pairs = {frozenset((m['a'], m['b'])) for m in matches if m.get('phase') == 'rs'}
    return [m for m in prev_matches if m['id'] not in ids
            and not (m.get('phase') == 'rs' and frozenset((m['a'], m['b'])) in pairs)]


def stamp_scripts(out, fixed=None):
    """add ?v=<content hash> to every <script src="./x.js"> of the built pages, so a deploy is picked up at once.
    fixed: {file: version} used instead of the file's hash (owcs-data.js: content_hash, the same v as owcs-ver.json).
    The owcs-test.js tag is dropped: it returns at once on the public site (10-24), so it was one wasted request.
    owcs-phase.js loads owcs-intl.js by itself (international mode): window.__owcsIntlV, set before it, is that file's hash,
    so the file is downloaded again only when it changed, not on every build (it used the build time)."""
    import hashlib
    ver = dict(fixed or {})
    intl_p = os.path.join(out, 'owcs-intl.js')
    intl_v = hashlib.sha1(open(intl_p, 'rb').read()).hexdigest()[:8] if os.path.isfile(intl_p) else None
    def tag(m):
        f = m.group(2)
        p = os.path.join(out, f)
        if f not in ver:
            ver[f] = hashlib.sha1(open(p, 'rb').read()).hexdigest()[:8] if os.path.isfile(p) else None
        return m.group(0) if not ver[f] else f'{m.group(1)}{f}?v={ver[f]}"'
    for f in os.listdir(out):
        if f.endswith('.html'):
            p = os.path.join(out, f)
            with open(p, encoding='utf-8') as fh:
                text = fh.read()
            new = re.sub(r'[ \t]*<script src="(?:\./)?owcs-test\.js"></script>\r?\n?', '', text)
            if intl_v:
                new = re.sub(r'(<script src="(?:\./)?owcs-phase\.js")', f'<script>window.__owcsIntlV="{intl_v}"</script>\n\\1', new, count=1)
            new = re.sub(r'(<script src="(?:\./)?)([\w.-]+\.js)"', tag, new)
            if new != text:
                with open(p, 'w', encoding='utf-8', newline='') as fh:
                    fh.write(new)


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    out = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else '_site'
    prev_url = sys.argv[sys.argv.index('--prev') + 1] if '--prev' in sys.argv else None
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    for f in SITE_FILES + [f for f in os.listdir(HERE) if f.startswith('owcs-') and f.endswith('.js') and f != 'owcs-data.js']:
        if os.path.exists(os.path.join(HERE, f)):
            shutil.copy2(os.path.join(HERE, f), os.path.join(out, f))
    try:   # the admin page also works from a phone at <site>/admin/: it saves through the GitHub API (needs the PC off)
        import admin_server
        os.makedirs(os.path.join(out, 'admin'))
        shutil.copy2(os.path.join(HERE, 'admin', 'index.html'), os.path.join(out, 'admin', 'index.html'))
        with open(os.path.join(out, 'admin', 'meta.json'), 'w', encoding='utf-8') as f:
            json.dump({'heroes': admin_server.heroes(), 'maps': admin_server.maps()}, f, ensure_ascii=False)
    except Exception as e:
        traceback.print_exc()
        print('! admin page not copied')
        flag(f'admin page not copied ({type(e).__name__}: {e})')

    now = datetime.datetime.now(b.KST)
    prev = fetch_prev(prev_url) if prev_url else None
    data = None
    if os.path.isdir(COLLECTOR):
        try:
            fast = '--fast' in sys.argv   # push with only live map scores: no Liquipedia / collector, just rebuild with the new scores
            if not fast:
                collect(prev, now, '--force-lp' in sys.argv)
            else:   # the collector's site data is not in its repo: rebuild it from the cached Liquipedia copy (no request)
                read_replays()
                node('collector/build.mjs')
            data = owcs_build.build(prev_live=(prev or {}).get('live'), out=out, records=False)
            print(f"built: {data['stage']} · {len(data['matches'])} matches · {sum(m['played'] for m in data['matches'])} played · "
                  f"{len(data['players'])} players · standings {[(s['a'], s['w'], s['l']) for s in data['standings']]}")
        except Exception as e:
            traceback.print_exc()
            print('! build failed: keeping the deployed data')
            flag(f'data build failed, the deployed data stays ({type(e).__name__}: {e})')
    if data is not None and prev and prev.get('stage') == data.get('stage'):
        # a Liquipedia page missing this run (429): keep the last deploy's brackets and playoff matches, not blank ones
        for k in ('bracket', 'lastStage', 'pastStages'):
            if not data.get(k) or (k == 'lastStage' and not data[k].get('columns')):
                if prev.get(k):
                    data[k] = prev[k]
                    print('! kept from the last deploy:', k)
        lost = carry_over(prev.get('matches', []), data['matches'])
        if lost:
            data['matches'] += lost
            print(f'! kept {len(lost)} matches from the last deploy:', ' '.join(m['id'] for m in lost))
    if data is None:
        data = prev
    if data is None and os.path.exists(os.path.join(HERE, 'owcs-data.js')):
        with open(os.path.join(HERE, 'owcs-data.js'), encoding='utf-8') as f:
            data = read_data(f.read())
    if data is None:
        sys.exit('no site data: build failed and nothing deployed yet')
    shutil.copytree(os.path.join(HERE, 'assets'), os.path.join(out, 'assets'))   # after the build: it may add Instagram photos

    if '--fast' in sys.argv and prev:   # live-score push: reuse the stream list and replays from the last deploy (seconds saved)
        data['live'], data['ytLive'] = prev.get('live', {}), prev.get('ytLive')
        data['lastStream'] = prev.get('lastStream', {})
        data['igReels'], data['igChecked'] = prev.get('igReels', []), prev.get('igChecked')
        vods = {m['id']: m['vod'] for m in prev.get('matches', []) if m.get('vod')}
        for m in data['matches']:
            if vods.get(m['id']):
                m['vod'] = vods[m['id']]
    else:   # replays: owcs_build.build already put one on each match (soop_vod, opened at the match start)
        data['live'] = b.live_status(data['players'])
        data['lastStream'] = b.last_streams(data['players'], (prev or {}).get('lastStream'))   # SOOP or CHZZK: whichever streamed last
        data['ytLive'] = b.yt_live((prev or {}).get('ytLive'), data['matches'], data.get('stageNo'))
        data['igReels'], data['igChecked'] = b.ig_reels((prev or {}).get('igReels'), (prev or {}).get('igChecked'))   # official Instagram reels, every build (5 min at most)
    stamp = now.isoformat(timespec='seconds')
    # a fast push copied the stream list: keep the time it was really checked, so the page's 30-minute stall warning still works
    data['liveChecked'] = prev.get('liveChecked') or stamp if '--fast' in sys.argv and prev else stamp
    same = prev and {k: v for k, v in prev.items() if k not in VOLATILE} == {k: v for k, v in data.items() if k not in VOLATILE}
    data['generated'] = prev['generated'] if same else stamp
    write_data(os.path.join(out, 'owcs-data.js'), data)
    ver = content_hash(data)   # owcs-ver.json: open pages poll it (owcs-datapoll.js); checked = the stream check time
    with open(os.path.join(out, 'owcs-ver.json'), 'w', encoding='utf-8') as f:
        json.dump({'v': ver, 'checked': data.get('liveChecked')}, f)
    b.write_ics(data, out)   # subscription calendar: only matches not played yet, so rebuild it on every run
    stamp_scripts(out, {'owcs-data.js': ver})   # after owcs-data.js is written: the same version goes on the pages
    print(f"live streams: {len(data['live'])} {sorted(data['live'])} · {'unchanged' if same else 'changed'} · generated {data['generated']}")
    site_urls.apply(out)   # short English addresses: owticker.com/schedule, /results ... (old names forward)


if __name__ == '__main__':
    main()
