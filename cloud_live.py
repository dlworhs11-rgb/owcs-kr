"""Build the public site folder for GitHub Pages and refresh the parts that need no PC.

Runs in GitHub Actions (.github/workflows/pages.yml) every ~10 min and on every push:
  1. copy the site files (pages, owcs-*.js, support.js, assets/) into --out
  2. take owcs-data.js as pushed from the PC (schedule, results, live map scores)
  3. refresh `live` (which players stream on CHZZK / SOOP) and match-day SOOP VOD links
  4. rebuild owcs-kr-upcoming.ics (calendar subscription, matches not played yet)
  5. set `liveChecked` = now; bump `generated` only when the content really changed,
     so open pages reload only when there is something new

Usage:
  python cloud_live.py --out _site [--prev https://<user>.github.io/<repo>/owcs-data.js]
"""
import json, os, shutil, sys, datetime, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.makedirs(os.path.join(HERE, 'data'), exist_ok=True)   # soop_vods() caches here
import owcs_cloud as b  # noqa: E402  (no local paths; build_owcs_data.py stays on the PC)

SITE_FILES = ['index.html', 'OWCS KR Home v6.dc.html', 'OWCS KR Player.dc.html', 'OWCS KR Results.dc.html',
              'OWCS KR 방송.html', 'OWCS KR 직관.html', 'support.js']
VOLATILE = ('generated', 'liveChecked')


def read_data(text):
    return json.loads(text[text.index('=') + 1:].strip().rstrip(';'))


def write_data(path, data):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// generated by build_owcs_data.py + cloud_live.py - do not edit\nwindow.OWCS = '
                + json.dumps(data, ensure_ascii=False) + ';\n')


def fetch_prev(url):
    try:
        req = urllib.request.Request(url + '?v=' + str(int(datetime.datetime.now().timestamp())), headers={'User-Agent': 'Mozilla/5.0'})
        return read_data(urllib.request.urlopen(req, timeout=15).read().decode('utf-8'))
    except Exception as e:
        print('previous deploy not readable:', e)
        return None


def main():
    out = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else '_site'
    prev_url = sys.argv[sys.argv.index('--prev') + 1] if '--prev' in sys.argv else None
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    for f in SITE_FILES + [f for f in os.listdir(HERE) if f.startswith('owcs-') and f.endswith('.js')]:
        if os.path.exists(os.path.join(HERE, f)):
            shutil.copy2(os.path.join(HERE, f), os.path.join(out, f))
    shutil.copytree(os.path.join(HERE, 'assets'), os.path.join(out, 'assets'))

    with open(os.path.join(HERE, 'owcs-data.js'), encoding='utf-8') as f:
        data = read_data(f.read())
    now = datetime.datetime.now(b.KST).isoformat(timespec='seconds')
    data['live'] = b.live_status(data['players'])
    vods = b.soop_vods()
    for m in data['matches']:
        if vods.get(m['day']):
            m['vod'] = vods[m['day']]
    data['liveChecked'] = now

    prev = fetch_prev(prev_url) if prev_url else None
    same = prev and {k: v for k, v in prev.items() if k not in VOLATILE} == {k: v for k, v in data.items() if k not in VOLATILE}
    data['generated'] = prev['generated'] if same else now
    write_data(os.path.join(out, 'owcs-data.js'), data)
    b.write_ics(data, out)   # subscription calendar: only matches not played yet, so rebuild it on every run
    print(f"live streams: {len(data['live'])} {sorted(data['live'])} · {'unchanged' if same else 'changed'} · generated {data['generated']}")


if __name__ == '__main__':
    main()
